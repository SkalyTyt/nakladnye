// Демо-файлы с вымышленным поставщиком: node tests/make-demo.js
const path = require('path'), fs = require('fs');
const XLSX = require('../vendor/xlsx.full.min.js');
XLSX.set_fs(fs);
const dir = path.join(__dirname, '..', 'demo');
fs.mkdirSync(dir, { recursive: true });

function ean13(seed) {
  const base = '460' + String(100000000 + ((seed * 7919) % 899999999)).padStart(9, '0');
  const sum = [...base].reduce((s, d, i) => s + Number(d) * (i % 2 ? 3 : 1), 0);
  return base + ((10 - (sum % 10)) % 10);
}

const goods = [
  ['Шампунь «Ромашка» для всех типов волос 400 мл', 3, 112.5],
  ['Бальзам-ополаскиватель «Ромашка» 400 мл', 3, 118.9],
  ['Гель для душа «Морской бриз» 500 мл', 4, 96.4],
  ['Мыло туалетное «Лаванда» 90 г', 12, 24.8],
  ['Зубная паста «Мятная свежесть» 100 мл', 6, 74.2],
  ['Зубная щётка средней жёсткости, синяя', 10, 39.9],
  ['Крем для рук «Алоэ» 75 мл', 5, 58.3],
  ['Средство для мытья посуды «Лимон» 900 мл', 6, 89.7],
  ['Губки для посуды, 5 шт', 8, 34.5],
  ['Пакеты для мусора 60 л, 20 шт', 5, 61.2],
  ['Отбеливатель с активным кислородом 500 г', 3, 102.4],
  ['Салфетки влажные детские, 100 шт', 6, 79.9],
];
const rows = goods.map(([name, qty, price], i) => ({ name, qty, price, sum: Math.round(qty * price * 100) / 100, bc: ean13(i + 11) }));
const total = Math.round(rows.reduce((s, r) => s + r.sum, 0) * 100) / 100;

// 1) счёт с ценами; штрихкоды есть только у части товаров, у одного — сразу два
const a = [
  ['ООО "Демо Поставщик"', '', '', '', 'Сч. №', '40702810000000000000'],
  ['ИНН 7700000000', 'КПП 770001001'],
  ['Получатель'],
  [],
  ['Счет на оплату № 1513 от 15 октября 2026 г.'],
  [],
  ['Поставщик:', 'ООО "Демо Поставщик"\n, ИНН 7700000000, КПП 770001001, 101000, г. Москва, ул. Примерная, д. 1'],
  ['Покупатель:', 'ИП Пример Покупатель, ИНН 000000000000'],
  [],
  ['№', 'Товары (работы, услуги)', 'Штрихкод', 'Кол-во', 'Ед.', 'Цена', 'Сумма'],
  ...rows.map((r, i) => [i + 1, r.name, i < 4 ? (i === 1 ? r.bc + ', ' + ean13(500) : r.bc) : '', r.qty, 'шт', r.price, r.sum]),
  [],
  ['', '', '', '', '', 'Итого:', total],
  ['', '', '', '', '', 'Без налога (НДС)', '-'],
  ['Всего наименований ' + rows.length + ', на сумму ' + total + ' руб.'],
];
// 2) отдельный файл от того же поставщика: названия чуть иначе + штрихкоды, без цен
const b = [['Наименование товара', 'Штрихкод'], ...rows.slice(4).reverse().map((r, i) => [i % 2 ? r.name.toUpperCase() : r.name.replace(/[«»]/g, '"'), r.bc])];

for (const [f, aoa, widths] of [['schet_na_oplatu_primer.xlsx', a, [6, 52, 30, 8, 6, 12, 12]], ['shtrihkody_primer.xlsx', b, [52, 16]]]) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws['!cols'] = widths.map((wch) => ({ wch }));
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Лист1');
  XLSX.writeFile(wb, path.join(dir, f));
}
